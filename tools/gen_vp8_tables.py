#!/usr/bin/env python3
"""Builds src/vp8_tables.h (VP8's fixed probabilities, from libvpx: BSD-3-Clause) and src/cedar_vp8_table.h (the
Allwinner engine's initial probability table, from mainline Cedrus: GPL-2.0-or-later, used by pmhwdec-cedard only).
usage: python3 tools/gen_vp8_tables.py <dir with libvpx's default_coef_probs.h, coefupdateprobs.h, entropymv.c and
       Linux's cedrus_vp8.c>"""
import os
import re
import sys

src = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def numbers(path, name):
    text = open(os.path.join(src, path), encoding="utf-8").read()
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    m = re.search(r"\b" + name + r"\b[^=]*=\s*\{", text)
    i, depth = m.end(), 1
    start = i
    while depth:
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        i += 1
    return [int(x, 0) for x in re.findall(r"0[xX][0-9a-fA-F]+|\d+", text[start:i])]


def nested(vals, dims, indent=0):
    if len(dims) == 1:
        return " " * indent + "{ " + ", ".join(str(v) for v in vals) + " }"
    step = len(vals) // dims[0]
    parts = [nested(vals[k * step:(k + 1) * step], dims[1:], indent + 1) for k in range(dims[0])]
    return " " * indent + "{\n" + ",\n".join(parts) + "\n" + " " * indent + "}"


def table(name, vals, dims):
    size = 1
    for d in dims:
        size *= d
    assert len(vals) == size, (name, len(vals), size)
    return "static const uint8_t " + name + "".join(f"[{d}]" for d in dims) + " =\n" + nested(vals, dims) + ";\n"


out = """/* SPDX-License-Identifier: BSD-3-Clause */
/* Generated by tools/gen_vp8_tables.py: do not edit. VP8's fixed probability tables, from libvpx (vp8/common):
 *   Copyright (c) 2010, Google Inc. / The WebM project authors. All rights reserved.
 * BSD-3-Clause: the license text is in licenses/LICENSE.libvpx.txt of this repository. */
#ifndef PMHW_VP8_TABLES_H
#define PMHW_VP8_TABLES_H
#include <stdint.h>

"""
out += table("vp8_default_coef_probs", numbers("default_coef_probs.h", "default_coef_probs"), [4, 8, 3, 11]) + "\n"
out += table("vp8_coef_update_probs", numbers("coefupdateprobs.h", "vp8_coef_update_probs"), [4, 8, 3, 11]) + "\n"
out += table("vp8_mv_update_probs", numbers("entropymv.c", "vp8_mv_update_probs"), [2, 19]) + "\n"
out += table("vp8_default_mv_context", numbers("entropymv.c", "vp8_default_mv_context"), [2, 19]) + "\n#endif\n"
open(os.path.join(root, "src", "vp8_tables.h"), "w", newline="\n").write(out)

vals = numbers("cedrus_vp8.c", "prob_table_init")
lines = ["    " + ", ".join(f"0x{v:02x}" for v in vals[i:i + 16]) + "," for i in range(0, len(vals), 16)]
out = """/* SPDX-License-Identifier: GPL-2.0-or-later */
/* Generated by tools/gen_vp8_tables.py: do not edit. The start of the video engine's VP8 probability memory, from
 * mainline Cedrus (cedrus_vp8.c, Copyright (c) 2019 Jernej Skrabec). pmhwdec-cedard only. */
static const uint8_t cedar_vp8_prob_init[] = {
""" + "\n".join(lines) + "\n};\n"
open(os.path.join(root, "src", "cedar_vp8_table.h"), "w", newline="\n").write(out)
print(len(vals), "bytes in the Allwinner table")
