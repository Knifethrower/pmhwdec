"""Generates src/ve_regs.h: the Allwinner video engine register facts cedar.c uses (offsets, bit positions, values),
resolved to plain numbers. Input: a reference register header (mainline cedrus_regs.h) used only as a lookup of facts;
nothing of its text is copied. The output is checked by compiling cedar.c against both and comparing the objects.
usage: python gen_ve_regs.py <reference header> <cedar.c> <out ve_regs.h>
(reference header: mainline drivers/staging/media/sunxi/cedrus/cedrus_regs.h, downloaded; not kept in this repo)"""
import re
import sys

ref_path, code_path, out_path = sys.argv[1:4]
ref = open(ref_path, encoding="utf-8").read()
code = open(code_path, encoding="utf-8").read()

# macro name -> (params, body), continuation lines joined
defs = {}
for m in re.finditer(r"^#define\s+(\w+)(\([^)]*\))?[ \t]*((?:[^\n\\]|\\\n)*)", ref, re.M):
    name, params, body = m.group(1), m.group(2), m.group(3).replace("\\\n", " ")
    defs[name] = (params, " ".join(body.split()))

used = sorted(set(re.findall(r"\bVE_[A-Z0-9_]+\b", code)) - {"VE_IP_H616"})


def fold(expr):
    """object-like macro body -> integer"""
    def sub(m):
        n = m.group(0)
        if n in defs and not defs[n][0]:
            return "(%d)" % fold(defs[n][1])
        return n
    e = re.sub(r"\b[A-Z][A-Z0-9_]*\b", sub, expr)
    e = re.sub(r"BIT\((\d+)\)", lambda m: "(1 << %s)" % m.group(1), e)
    e = re.sub(r"GENMASK\((\d+),\s*(\d+)\)", lambda m: "(((1 << (%s - %s + 1)) - 1) << %s)" % (m.group(1), m.group(2), m.group(2)), e)
    e = e.replace("(unsigned long)", "")
    return int(eval(e, {"__builtins__": {}}))   # only numbers and operators remain


lines = []
for name in used:
    params, body = defs[name]
    if not params:
        lines.append(("const", name, fold(body)))
        continue
    m = re.fullmatch(r"SHIFT_AND_MASK_BITS\(\s*(\w+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)", body)
    if m:
        lines.append(("field", name, (int(m.group(2)), int(m.group(3)))))
        continue
    m = re.fullmatch(r"\(\(\((\w+)\) << (\d+)\) & GENMASK\((\d+), (\d+)\)\)", body)
    if m:
        lines.append(("field", name, (int(m.group(3)), int(m.group(4)))))
        continue
    m = re.fullmatch(r"\(\(\((\w+)\) >> (\d+)\) & GENMASK\((\d+), (\d+)\)\)", body)
    if m:
        lines.append(("shr_mask", name, (int(m.group(2)), int(m.group(3)), int(m.group(4)))))
        continue
    m = re.fullmatch(r"\(\((\w+)\) >> (\d+)\)", body)
    if m:
        lines.append(("shr", name, int(m.group(2))))
        continue
    if name == "VE_H264_VLD_ADDR_VAL":
        lines.append(("raw", name, "(((a) & 0x0ffffff0) | ((a) >> 28))"))
        continue
    if name == "VE_H264_TRIGGER_TYPE_BIN_LENS":
        lines.append(("raw", name, "VE_FIELD((a) - 1, 18, 16)"))
        continue
    if name == "VE_VP8_FSIZE_WIDTH":
        lines.append(("raw", name, "VE_FIELD(((a) + 15) / 16, 15, 8)"))
        continue
    if name == "VE_VP8_FSIZE_HEIGHT":
        lines.append(("raw", name, "VE_FIELD(((a) + 15) / 16, 7, 0)"))
        continue
    sys.exit("unhandled macro %s: %s" % (name, body))

out = ["/* SPDX-License-Identifier: GPL-2.0-or-later */",
       "/* Allwinner video engine (H6 / H616 / H700 / A133 family): the register offsets, bit fields and values cedar.c uses.",
       " * Hardware facts only, as plain numbers; generated by tools/gen_ve_regs.py, which checks that cedar.c compiles to the",
       " * same object code as with mainline Cedrus' header (the source of these facts). */",
       "#ifndef PMHWDEC_VE_REGS_H", "#define PMHWDEC_VE_REGS_H", "",
       "/* value v placed in bits hi..lo */",
       "#define VE_FIELD(v, hi, lo) ((((unsigned long)(v)) << (lo)) & (((~0UL) >> (63 - (hi))) & ((~0UL) << (lo))))", ""]
for kind, name, val in lines:
    if kind == "const":
        out.append("#define %-70s 0x%x" % (name, val))
    elif kind == "field":
        out.append("#define %-70s VE_FIELD(v, %d, %d)" % (name + "(v)", val[0], val[1]))
    elif kind == "shr_mask":
        out.append("#define %-70s (((a) >> %d) & VE_FIELD(~0UL, %d, %d))" % (name + "(a)", val[0], val[1], val[2]))
    elif kind == "shr":
        out.append("#define %-70s ((a) >> %d)" % (name + "(a)", val))
    else:
        out.append("#define %-70s %s" % (name + "(a)", val))
out += ["", "#endif", ""]
open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("%d definitions written to %s" % (len(lines), out_path))
